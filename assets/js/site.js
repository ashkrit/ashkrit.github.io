/* ---------- helpers ---------- */

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text != null) node.textContent = text;
  return node;
}

function link(href, text, className) {
  const a = el('a', className, text);
  a.href = href;
  if (!href.startsWith('#') && !href.startsWith('mailto:')) {
    a.target = '_blank';
    a.rel = 'noopener';
  }
  return a;
}

function formatDate(iso) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-GB', { year: 'numeric', month: 'short', day: 'numeric' });
}

/** A profile field still carrying its TODO marker is treated as unset. */
const isTodo = (value) => typeof value === 'string' && value.trim().toUpperCase().startsWith('TODO');
const real   = (value) => (typeof value === 'string' && value.trim() && !isTodo(value) ? value.trim() : '');

function showEmpty(container, message, href, linkText) {
  container.textContent = '';
  const box = el('div', 'empty');
  box.append(el('p', null, message));
  if (href) {
    const p = el('p');
    p.append(link(href, linkText, 'btn'));
    box.append(p);
  }
  container.append(box);
}

async function loadJSON(path) {
  const res = await fetch(path, { cache: 'no-cache' });
  if (!res.ok) throw new Error(`${path} → HTTP ${res.status}`);
  return res.json();
}

