function renderStack(profile) {
  const container = $('#stack-list');
  if (!container) return;

  const stack = profile.stack || [];
  if (!stack.length) {
    $('#stack')?.remove();
    return;
  }

  stack.forEach((group) => {
    const card = el('div', 'card stack-card');

    const header = el('div', 'stack-header');
    const svgHTML = STACK_ICONS[group.category] || STACK_ICONS["Languages & Runtimes"];
    const iconBox = el('div', 'stack-icon-box');
    iconBox.innerHTML = svgHTML;
    header.append(iconBox);

    const h3 = el('h3', 'card-title', group.category);
    header.append(h3);
    card.append(header);

    if (group.skills?.length) {
      const list = el('div', 'card-labels');
      group.skills.forEach((skill) => {
        const tag = el('span', 'tag tag-icon');
        if (TECH_IMAGE_MAP[skill]) {
          tag.classList.add('tag-brand-only');
          tag.setAttribute('title', skill);
          tag.setAttribute('aria-label', skill);
          const img = el('img', 'tech-brand-img');
          img.src = TECH_IMAGE_MAP[skill];
          img.alt = skill;
          tag.append(img);
        } else {
          const iconSVG = TECH_ICONS[skill] || `<span class="tag-bullet"></span>`;
          const span = el('span', 'tag-svg-wrap');
          span.innerHTML = iconSVG;
          tag.append(span);
          tag.append(el('span', 'tag-text', skill));
        }
        list.append(tag);
      });
      card.append(list);
    }
    container.append(card);
  });
}

function renderBookshelf(profile) {
  const container = $('#bookshelf-list');
  if (!container) return;

  const bookshelf = profile.bookshelf || [];
  if (!bookshelf.length) {
    $('#bookshelf')?.remove();
    return;
  }

  bookshelf.forEach((section) => {
    const groupWrap = el('div', 'bookshelf-group');
    groupWrap.append(el('h3', 'focus-title', section.category));

    const grid = el('div', 'cards bookshelf-grid');
    (section.items || []).forEach((item) => {
      const card = el('div', 'card book-card');
      const h4 = el('h4', 'card-title', item.title);
      card.append(h4);
      card.append(el('p', 'book-author', `by ${item.author}`));
      if (item.note) card.append(el('p', 'card-excerpt', item.note));
      grid.append(card);
    });
    groupWrap.append(grid);
    container.append(groupWrap);
  });
}

const LINK_LABELS = {
  blog:     'Blog',
  github:   'GitHub',
  linkedin: 'LinkedIn',
  twitter:  'Twitter',
  email:    'Email',
};

function renderLinks(links) {
  const hero    = $('#hero-links');
  const contact = $('#contact-links');

  const entries = Object.entries(LINK_LABELS)
    .map(([key, label]) => [key, label, real(links[key])])
    .filter(([, , href]) => href);

  entries.forEach(([key, label, href], i) => {
    const url = key === 'email' ? `mailto:${href}` : href;
    if (hero) {
      hero.append(link(url, key === 'email' ? href : `${label} ↗`, i === 0 ? 'btn btn-primary' : 'btn'));
    }
    if (contact) {
      contact.append(link(url, key === 'email' ? href : label, 'btn'));
    }
  });
}

function renderExperience(profile) {
  const list = $('#timeline');
  if (list) {
    const roles = (profile.experience || []).filter((r) => real(r.role) && real(r.company));
    if (roles.length) {
      roles.forEach((r) => list.append(roleItem(r)));
    } else {
      list.replaceWith(Object.assign(el('p', 'section-sub'), {
        textContent: 'Experience details coming soon.',
      }));
    }
  }

  const eduItems = (profile.education || []).filter((e) => real(e.school));
  const block = $('#education-block');
  const eduList = $('#education');
  if (block && eduList && eduItems.length) {
    block.hidden = false;
    eduItems.forEach((e) => {
      const li = el('li');
      const period = real(e.period);
      if (period) li.append(el('p', 'tl-period', period));
      li.append(el('h4', 'tl-role', real(e.school)));
      const degree = real(e.degree);
      if (degree) li.append(el('p', 'tl-org', degree));
      eduList.append(li);
    });
  }
}

function roleItem(r) {
  const li = el('li');
  if (r.current) li.classList.add('is-current');

  const period = real(r.period);
  if (period) li.append(el('p', 'tl-period', period));

  li.append(el('h3', 'tl-role', real(r.role)));

  const org = [real(r.company), real(r.location)].filter(Boolean).join(' · ');
  if (org) li.append(el('p', 'tl-org', org));

  const summary = real(r.summary);
  if (summary) li.append(el('p', 'tl-summary', summary));

  return li;
}

