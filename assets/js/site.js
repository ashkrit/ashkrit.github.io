/* ============================================================
   ashkrit.github.io — site behaviour
   Vanilla ES module. No dependencies.

   Data is fetched same-origin from data/*.json. Those files are
   regenerated by scripts/sync.py in CI rather than fetched from
   the browser, because Blogger's feed sends no CORS header.

   Everything from those files is remote content, so it is
   inserted with textContent — never innerHTML.
   ============================================================ */

const $  = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

const POSTS_PER_PAGE = 9;
const REPOS_PER_PAGE = 9;
const TOP_LABELS     = 10;

/* ---------- helpers ---------- */

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text != null) node.textContent = text;
  return node;
}

function link(href, text, className) {
  const a = el('a', className, text);
  a.href = href;
  if (!href.startsWith('#') && !href.startsWith('mailto:')) {
    a.target = '_blank';
    a.rel = 'noopener';
  }
  return a;
}

function formatDate(iso) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-GB', { year: 'numeric', month: 'short', day: 'numeric' });
}

/** A profile field still carrying its TODO marker is treated as unset. */
const isTodo = (value) => typeof value === 'string' && value.trim().toUpperCase().startsWith('TODO');
const real   = (value) => (typeof value === 'string' && value.trim() && !isTodo(value) ? value.trim() : '');

function showEmpty(container, message, href, linkText) {
  container.textContent = '';
  const box = el('div', 'empty');
  box.append(el('p', null, message));
  if (href) {
    const p = el('p');
    p.append(link(href, linkText, 'btn'));
    box.append(p);
  }
  container.append(box);
}

async function loadJSON(path) {
  const res = await fetch(path, { cache: 'no-cache' });
  if (!res.ok) throw new Error(`${path} → HTTP ${res.status}`);
  return res.json();
}

/* ---------- theme ---------- */

const SUN = 'M12 17a5 5 0 1 1 0-10 5 5 0 0 1 0 10Zm0-14v2m0 14v2M4.2 4.2l1.4 1.4m12.8 12.8 1.4 1.4M3 12h2m14 0h2M4.2 19.8l1.4-1.4M17 6l1.4-1.4';
const MOON = 'M21 12.8A9 9 0 1 1 11.2 3a7 7 0 0 0 9.8 9.8Z';

function initTheme() {
  const btn  = $('#theme-toggle');
  const icon = $('.theme-icon');
  if (!btn || !icon) return;

  const svgNS = 'http://www.w3.org/2000/svg';
  const svg   = document.createElementNS(svgNS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '1.8');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.style.width = '100%';
  svg.style.height = '100%';
  const path = document.createElementNS(svgNS, 'path');
  svg.append(path);
  icon.append(svg);

  const systemDark = () => window.matchMedia('(prefers-color-scheme: dark)').matches;
  const isDark = () => {
    const set = document.documentElement.dataset.theme;
    return set ? set === 'dark' : systemDark();
  };

  const paint = () => {
    // Show the icon for the theme the button switches *to*.
    path.setAttribute('d', isDark() ? SUN : MOON);
    btn.setAttribute('aria-label', isDark() ? 'Switch to light theme' : 'Switch to dark theme');
  };

  btn.addEventListener('click', () => {
    const next = isDark() ? 'light' : 'dark';
    document.documentElement.dataset.theme = next;
    try { localStorage.setItem('theme', next); } catch (e) { /* private mode */ }
    paint();
  });

  window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', paint);
  paint();
}

/* ---------- profile ---------- */

function renderProfile(profile) {
  const map = {
    name: profile.name,
    role: profile.role,
    company: profile.company,
    location: profile.location,
    tagline: profile.tagline,
  };

  $$('[data-profile]').forEach((node) => {
    const value = real(map[node.dataset.profile]);
    if (value) node.textContent = value;
    else if (!node.textContent.trim()) node.remove();
  });

  const name = real(profile.name);
  if (name) {
    document.title = `${name} — Engineering, systems & AI`;
    const mark = $('.brand-mark');
    if (mark) {
      mark.textContent = name.split(/\s+/).map((w) => w[0]).join('').slice(0, 2).toUpperCase();
    }
  }

  // Bio paragraphs
  const bio = $('#about-bio');
  if (bio) {
    (profile.bio || []).filter((p) => real(p)).forEach((p) => bio.append(el('p', null, p)));
  }

  // Focus tags
  const focus = $('#focus-list');
  if (focus) {
    const items = (profile.focus || []).filter((f) => real(f));
    if (items.length) items.forEach((f) => focus.append(el('li', null, f)));
    else focus.closest('.focus')?.remove();
  }

  renderLinks(profile.links || {});
  renderExperience(profile);
}

const LINK_LABELS = {
  blog:     'Blog',
  github:   'GitHub',
  linkedin: 'LinkedIn',
  twitter:  'Twitter',
  email:    'Email',
};

function renderLinks(links) {
  const hero    = $('#hero-links');
  const contact = $('#contact-links');

  const entries = Object.entries(LINK_LABELS)
    .map(([key, label]) => [key, label, real(links[key])])
    .filter(([, , href]) => href);

  entries.forEach(([key, label, href], i) => {
    const url = key === 'email' ? `mailto:${href}` : href;
    if (hero) {
      hero.append(link(url, key === 'email' ? href : `${label} ↗`, i === 0 ? 'btn btn-primary' : 'btn'));
    }
    if (contact) {
      contact.append(link(url, key === 'email' ? href : label, 'btn'));
    }
  });
}

function renderExperience(profile) {
  const list = $('#timeline');
  if (list) {
    const roles = (profile.experience || []).filter((r) => real(r.role) && real(r.company));
    if (roles.length) {
      roles.forEach((r) => list.append(roleItem(r)));
    } else {
      list.replaceWith(Object.assign(el('p', 'section-sub'), {
        textContent: 'Experience details coming soon.',
      }));
    }
  }

  const eduItems = (profile.education || []).filter((e) => real(e.school));
  const block = $('#education-block');
  const eduList = $('#education');
  if (block && eduList && eduItems.length) {
    block.hidden = false;
    eduItems.forEach((e) => {
      const li = el('li');
      const period = real(e.period);
      if (period) li.append(el('p', 'tl-period', period));
      li.append(el('h4', 'tl-role', real(e.school)));
      const degree = real(e.degree);
      if (degree) li.append(el('p', 'tl-org', degree));
      eduList.append(li);
    });
  }
}

function roleItem(r) {
  const li = el('li');
  if (r.current) li.classList.add('is-current');

  const period = real(r.period);
  if (period) li.append(el('p', 'tl-period', period));

  li.append(el('h3', 'tl-role', real(r.role)));

  const org = [real(r.company), real(r.location)].filter(Boolean).join(' · ');
  if (org) li.append(el('p', 'tl-org', org));

  const summary = real(r.summary);
  if (summary) li.append(el('p', 'tl-summary', summary));

  return li;
}

/* ---------- posts ---------- */

function renderPosts(data) {
  const list      = $('#post-list');
  const countNode = $('#post-count');
  const moreBtn   = $('#post-more');
  const chips     = $('#label-chips');
  const search    = $('#post-search');

  const posts = data.posts || [];
  if (!posts.length) {
    showEmpty(list, 'Posts could not be loaded.', 'https://ashkrit.blogspot.com', 'Read the blog ↗');
    return;
  }

  let activeLabel = null;
  let query = '';
  let shown = POSTS_PER_PAGE;

  // Topic chips, most-used labels first.
  const topLabels = Object.entries(data.labels || {}).slice(0, TOP_LABELS);
  const allChip = makeChip('All', null, posts.length);
  allChip.setAttribute('aria-pressed', 'true');
  chips.append(allChip);
  topLabels.forEach(([label, n]) => chips.append(makeChip(label, label, n)));

  function makeChip(text, value, count) {
    const b = el('button', 'chip', text);
    b.type = 'button';
    b.setAttribute('aria-pressed', 'false');
    if (count != null) {
      const c = el('span', 'chip-count', String(count));
      b.append(c);
    }
    b.addEventListener('click', () => {
      activeLabel = activeLabel === value ? null : value;
      shown = POSTS_PER_PAGE;
      $$('.chip', chips).forEach((other) => other.setAttribute('aria-pressed', 'false'));
      const target = activeLabel === null ? allChip : b;
      target.setAttribute('aria-pressed', 'true');
      draw();
    });
    return b;
  }

  function matches(post) {
    if (activeLabel && !post.labels.includes(activeLabel)) return false;
    if (!query) return true;
    const haystack = `${post.title} ${post.excerpt} ${post.labels.join(' ')}`.toLowerCase();
    return haystack.includes(query);
  }

  function draw() {
    const filtered = posts.filter(matches);
    list.textContent = '';

    if (!filtered.length) {
      showEmpty(list, 'No posts match that filter.');
      countNode.textContent = '';
      moreBtn.hidden = true;
      return;
    }

    filtered.slice(0, shown).forEach((post, index) => list.append(postCard(post, index)));

    const visible = Math.min(shown, filtered.length);
    countNode.textContent = `Showing ${visible} of ${filtered.length} post${filtered.length === 1 ? '' : 's'}`;
    moreBtn.hidden = visible >= filtered.length;
  }

  moreBtn.addEventListener('click', () => {
    shown += POSTS_PER_PAGE;
    draw();
  });

  let debounce;
  search.addEventListener('input', () => {
    clearTimeout(debounce);
    debounce = setTimeout(() => {
      query = search.value.trim().toLowerCase();
      shown = POSTS_PER_PAGE;
      draw();
    }, 120);
  });

  draw();
}

function postCard(post, index) {
  const card = el('article', 'card');
  const isFeatured = index === 0;

  if (isFeatured && post.thumbnail) {
    card.classList.add('card-featured');
  }

  if (post.thumbnail) {
    const imgWrap = el('div', 'card-image-wrap');
    const img = el('img', 'card-image');
    // Upgrade Blogger 72px thumbnail to crisp high-res image banner
    const highResUrl = post.thumbnail.replace(/=s72(-c|-w\d+-h\d+-c)?/, '=w800-h450-c');
    img.src = highResUrl;
    img.alt = post.title;
    img.loading = isFeatured ? 'eager' : 'lazy';
    imgWrap.append(img);
    card.append(imgWrap);
  }

  const content = el('div', 'card-content');

  const date = formatDate(post.published);
  if (date) content.append(el('p', 'card-date', date));

  const h3 = el('h3', 'card-title');
  h3.append(link(post.url, post.title));
  content.append(h3);

  if (post.excerpt) content.append(el('p', 'card-excerpt', post.excerpt));

  if (post.labels?.length) {
    const tags = el('div', 'card-labels');
    post.labels.slice(0, 4).forEach((l) => tags.append(el('span', 'tag', l)));
    content.append(tags);
  }

  card.append(content);
  return card;
}

/* ---------- repos ---------- */

function renderRepos(data) {
  const list    = $('#repo-list');
  const moreBtn = $('#repo-more');

  const repos = data.repos || [];
  if (!repos.length) {
    showEmpty(list, 'Repositories could not be loaded.', 'https://github.com/ashkrit', 'Browse GitHub ↗');
    return;
  }

  let shown = REPOS_PER_PAGE;

  function draw() {
    list.textContent = '';
    repos.slice(0, shown).forEach((repo) => list.append(repoCard(repo)));
    moreBtn.hidden = shown >= repos.length;
  }

  moreBtn.addEventListener('click', () => {
    shown += REPOS_PER_PAGE;
    draw();
  });

  draw();
}

function repoCard(repo) {
  const card = el('article', 'card');

  const h3 = el('h3', 'repo-name');
  h3.append(link(repo.url, repo.name));
  card.append(h3);

  card.append(el('p', 'card-excerpt', repo.description || 'No description.'));

  const meta = el('div', 'repo-meta');
  if (repo.language) {
    const lang = el('span');
    lang.append(el('i', 'lang-dot'), document.createTextNode(repo.language));
    meta.append(lang);
  }
  if (repo.stars > 0) meta.append(el('span', null, `★ ${repo.stars}`));
  if (repo.pushed_at) meta.append(el('span', null, `Updated ${formatDate(repo.pushed_at)}`));
  if (meta.childElementCount) card.append(meta);

  return card;
}

/* ---------- stats ---------- */

function renderStats(posts, repos) {
  // A tile with no number reads as broken, so drop the tile rather than
  // leaving the placeholder dash behind.
  const set = (id, value) => {
    const node = $(id);
    if (!node) return;
    if (value == null) node.closest('.stat')?.remove();
    else node.textContent = String(value);
  };

  set('#stat-posts', posts ? posts.total ?? posts.posts?.length ?? 0 : null);
  set('#stat-topics', posts ? Object.keys(posts.labels || {}).length : null);
  set('#stat-repos', repos ? repos.total ?? repos.repos?.length ?? 0 : null);
  set('#stat-stars', repos ? (repos.repos || []).reduce((sum, r) => sum + (r.stars || 0), 0) : null);

  const stats = $('#stats');
  if (stats && !stats.childElementCount) stats.remove();
}

/* ---------- boot ---------- */

async function init() {
  initTheme();

  const yearNode = $('#year');
  if (yearNode) yearNode.textContent = String(new Date().getFullYear());

  const [profile, posts, repos] = await Promise.all([
    loadJSON('data/profile.json').catch((e) => { console.error(e); return null; }),
    loadJSON('data/posts.json').catch((e) => { console.error(e); return null; }),
    loadJSON('data/repos.json').catch((e) => { console.error(e); return null; }),
  ]);

  if (profile) renderProfile(profile);

  if (posts) renderPosts(posts);
  else showEmpty($('#post-list'), 'Posts could not be loaded right now.', 'https://ashkrit.blogspot.com', 'Read the blog ↗');

  if (repos) renderRepos(repos);
  else showEmpty($('#repo-list'), 'Repositories could not be loaded right now.', 'https://github.com/ashkrit', 'Browse GitHub ↗');

  renderStats(posts, repos);
}

init();
